def find_shape(slide, old, name=None):
    for sh in slide.shapes:
        if not sh.has_text_frame:
            continue
        if name and sh.name != name:
            continue
        if sh.text_frame.text.strip() == old.strip():
            return sh
    return None


def set_text(shape, new, keep_style_of_run=True):
    tf = shape.text_frame
    p = tf.paragraphs[0]
    if not p.runs:
        return False
    r0 = p.runs[0]
    r0.text = new
    for r in p.runs[1:]:
        r._r.getparent().remove(r._r)
    return True


def rep(slide, old, new, tag, name=None):
    sh = find_shape(slide, old, name)
    if sh is None:
        print("  ! MISS", tag, repr(old[:36]))
        return 0
    set_text(sh, new)
    print("  ok", tag)
    return 1


